function buildIcon(name, color) {
  const path = ICON_PATHS[name] || ''
  const strokeColor = color || COLORS.text2
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 24 24" fill="none" stroke="' + strokeColor + '" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + path + '</svg>'
  // 使用 encodeURIComponent 替代 base64，在小程序 3.17+ 更稳定
  return 'data:image/svg+xml,' + encodeURIComponent(svg)
}

// 构造填充色图标（fill=color, stroke=none），用于实心星星等
function buildFilledIcon(name, color) {
  const path = ICON_PATHS[name] || ''
  const fillColor = color || COLORS.text2
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 24 24" fill="' + fillColor + '" stroke="none">' + path + '</svg>'
  return 'data:image/svg+xml,' + encodeURIComponent(svg)
}

// 批量构建一组图标（同色）
function buildIconSet(names, color) {
  const result = {}
  names.forEach(name => {
    result[name] = buildIcon(name, color)
  })
  return result
}

